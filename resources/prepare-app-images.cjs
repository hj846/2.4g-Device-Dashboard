// Copy verified local artwork into the app so packaged builds work offline.
const fs = require('node:fs');
const path = require('node:path');
const crypto = require('node:crypto');
const app = path.resolve(__dirname, '../desktop-demo');
const {entries} = require('./manifest.json');
const catalog = {};
const variants = {};
const normalize = value => value.toUpperCase().replace(/[^A-Z0-9]/g, '');
function add(brand, model, entry) {
  const buffer = fs.readFileSync(path.join(__dirname, entry.file));
  if (crypto.createHash('sha256').update(buffer).digest('hex') !== entry.sha256) throw Error(entry.file);
  const relative = 'assets/products/official/' + entry.file;
  const target = path.join(app, relative);
  fs.mkdirSync(path.dirname(target), {recursive:true});
  fs.writeFileSync(target, buffer);
  (catalog[brand] ||= {})[normalize(model)] = relative.split('/').map(encodeURIComponent).join('/');
  return catalog[brand][normalize(model)];
}
const rapoo = entries.filter(e => e.brand === 'rapoo');
for(const model of new Set(entries.filter(e=>e.brand==='mchose').map(e=>e.model))){
  const choices=entries.filter(e=>e.brand==='mchose'&&e.model===model).sort((a,b)=>Number(b.color==='黑色')-Number(a.color==='黑色'));
  (variants.MCHOSE ||= {})[normalize(model)]=choices.map(e=>({src:add('MCHOSE',model,e),color:e.color}));
  catalog.MCHOSE[normalize(model)]=variants.MCHOSE[normalize(model)][0].src;
}
for (const model of new Set(rapoo.map(e => e.model))) {
  const choices = rapoo.filter(e => e.model === model && /\/thumb_/.test(e.file));
  const entry = choices.find(e => /\/thumb_Black\.png$/.test(e.file)) || choices[0];
  if (entry) {
    const ordered = [entry, ...choices.filter(e=>e!==entry)];
    (variants.RAPOO ||= {})[normalize(model)] = ordered.map(e=>({
      src:add('RAPOO',model,e), color:path.basename(e.file,'.png').replace(/^thumb_/,'')
    }));
    catalog.RAPOO[normalize(model)] = variants.RAPOO[normalize(model)][0].src;
  }
}
for (const entry of entries.filter(e => e.brand === 'logitech')) add('LOGITECH', entry.model, entry);
add('AULA', 'F75', entries.find(e => e.brand === 'aula' && e.model === 'F75'));
for(const brand of ['steelseries','morkblade'])for(const e of entries.filter(e=>e.brand===brand))add(brand.toUpperCase(),e.model,e);
if(catalog.STEELSERIES)catalog.STEELSERIES.ARCTISNOVA5=catalog.STEELSERIES.ARCTISNOVA5WIRELESS;
if(catalog.MORKBLADE)catalog.MORKBLADE.BOLDTKL=catalog.MORKBLADE.BOLDTKLHE;
// Explicit families only: never group generations or unrelated editions by prefix.
for(const names of [
  ['g203_black','g203_white','g203_blue','g203_lilac'],
  ['g305_black','g305_white','g305_blue','g305_lilac','g305_mint'],
  ['pro_x_wireless_mouse','pro_x_wireless_mouse_white','pro_x_wireless_mouse_magenta'],
  ['g535_black','g535_white','g535_mint'],
  ['g733','g733_white','g733_blue','g733_lilac'],
  ['g915_tkl','g915_tkl_white']
]) {
  const choices=names.filter(n=>catalog.LOGITECH[normalize(n)]).map((n,i)=>({src:catalog.LOGITECH[normalize(n)],color:i===0?'Black':n.split('_').at(-1)}));
  for(const name of names)(variants.LOGITECH ||= {})[normalize(name)]=choices;
}
const aliases = {
  G102G203:'g203_black', G102:'g203_black', G203:'g203_black',
  G305:'g305_black', G403HERO:'g403_wired',
  G502LIGHTSPEED:'g502_wireless', G502:'g502_core',
  GPROKEYBOARD:'pro_keyboard', GPROWIRELESS:'pro_wireless_mouse_black',
  PROWIRELESS:'pro_wireless_mouse_black', GPROMOUSE:'pro_mouse',
  GPROXSUPERLIGHT:'pro_x_wireless_mouse', PROXSUPERLIGHT:'pro_x_wireless_mouse'
};
for (const [alias, file] of Object.entries(aliases)) {
  const src = catalog.LOGITECH[normalize(file)];
  if (!src) throw Error('Missing alias target: ' + file);
  catalog.LOGITECH[alias] = src;
  if(variants.LOGITECH[normalize(file)])variants.LOGITECH[alias]=variants.LOGITECH[normalize(file)];
}
const source = `// Generated by resources/prepare-app-images.cjs. Exact model matches only.\n(function(root){\nconst catalog=${JSON.stringify(catalog,null,2)};\nfunction key(device){\n const brand=String(device.brandKey||'').toUpperCase();\n const model=String(device.model||'').replace(/（上次识别）|\\(上次识别\\)/g,'').replace(/^(?:雷柏|狼蛛|罗技|迈从|墨刃|SteelSeries|Mork[ -]?Blade|MCHOSE|Rapoo|AULA|Logitech)(?=\\s|[A-Z0-9])/i,'').replace(/\\s+(?:2\\.4\\s*G(?:Hz)?|USB|Bluetooth)(?:\\s.*)?$/i,'').toUpperCase().replace(/[^A-Z0-9]/g,'');\n return {brand,model};\n}\nconst variants=${JSON.stringify(variants,null,2)};\nfunction find(device){const {brand,model}=key(device);return catalog[brand]?.[model]||null}\nfunction colors(device){const {brand,model}=key(device);return variants[brand]?.[model]||[]}\nroot.deviceArtwork={find,colors,catalog};\nif(typeof module!=='undefined')module.exports=root.deviceArtwork;\n})(globalThis);\n`;
fs.writeFileSync(path.join(app,'product-images.js'), source);
console.log('Prepared official artwork:', Object.fromEntries(Object.entries(catalog).map(([k,v])=>[k,Object.keys(v).length])));
